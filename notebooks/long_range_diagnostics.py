            _a = (_v1["sets"].get(SET) or {}).get("classes", {}).get(CLS, {}).get(_m, (None,))[0]
            _b = (_v2["sets"].get(SET) or {}).get("classes", {}).get(CLS, {}).get(_m, (None,))[0]
            _pair.append((_lab, _a, _b))

