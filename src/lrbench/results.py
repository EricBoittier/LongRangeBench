"""Committed result rows: ``results/<set>/<model>.json``, their set cards, the validator and the generated tables.

A result JSON from ``lrbench eval`` is the unit of exchange, but it is not fit to commit: it records the host, the
absolute paths of the weights and the data, and every structure's prediction if asked to. A **row** is the part of
it a table needs -- one model on one set -- plus the provenance that makes the number auditable (weight sha256, data
sha256, code commit, seeds, failures, level match), with every directory prefix stripped. Rows are written by
``lrbench results add``, never by hand, and every table built from them is regenerated by ``lrbench results render``.

Two files describe what a row may be scored against:

- ``results/sets.json``: one **set card** per set -- reference level, licence, whether it is public, and every data
  revision (jsonl + groups sha256) ever scored. Adding curves to a set is a new revision: rows on the old one stay
  valid but are marked *stale* in the tables until re-scored, so rows on different data are never silently compared.
- ``results/private/``: git-ignored. Rows for unreleased models and anything scored on internal-only data live
  there, with their own ``sets.json``; the tools treat it exactly like the public tree but nothing in it is committed.

The schema is ``lrbench-row/1`` (:data:`ROW_KEYS`); docs/results.md is the human description.
"""
from __future__ import annotations

import argparse
import datetime
import json
import os
import re
import subprocess
import sys
from typing import Dict, List, Optional

SCHEMA = "lrbench-row/1"
ROW_KEYS = {"schema", "set", "model", "label", "members", "model_level", "reference_level", "level_mismatch",
            "seeds", "evidence", "n_failed", "n_scored", "date", "code_commit", "lrbench_version", "data", "argv",
            "metrics", "notes"}
CARD_KEYS = {"reference_level", "licence", "public", "description", "revisions"}
#: Below this fraction scored, a row's numbers describe too little of the set to quote, and the table says so.
#:
#: The fraction is ``n_scored / (n_scored + n_failed)``. It is an estimate, not an identity: ``n_failed`` is the
#: largest failure count any block of the set reports and can count predictions where ``n_scored`` counts groups.
#: It is still the right order of magnitude, and the order of magnitude is the point -- PET-SPICE-S on the trimers
#: scored 9 of some 42, which the old flag reported only as "33 failed", a phrasing that reads as a footnote rather
#: than as what it is: a number computed on a fifth of the task. Coverage this low is almost never a random sample
#: either; these failures are whole systems dropped for an unsupported element.
MIN_COVERAGE = 0.75

#: seeds needed before a row is a claim rather than a screen (the house rule: four seeds make a claim)
CLAIM_SEEDS = 4
BEGIN, END = "<!-- BEGIN lrbench results render: {} -->", "<!-- END lrbench results render: {} -->"
PRIVATE = "private"

_HEX = re.compile(r"^[0-9a-f]{64}$")
_COMMIT = re.compile(r"^[0-9a-f]{7,40}$")
_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._+-]*$")
# a directory prefix anchored at "/", "~/", "$VAR/", "./" or "../" -- never "wB97M-V/def2-TZVPD", "meV/A" or a URL
_DIRS = re.compile(r"(?<![\w:/.\-)])(?:(?:~|\$\{?\w+\}?|\.\.?)/(?:[\w.\-]+/)*|/(?:[\w.\-]+/)+)")
# what the validator refuses anywhere in a row: an absolute or home-relative directory
_ABS = re.compile(r"(?<![\w:/.\-])(?:~/|/(?:[\w.\-]+/)+|[A-Za-z]:\\)")


# --------------------------------------------------------------------------------------------------------- helpers

def strip_dirs(s: str) -> str:
    """Drop absolute, home- and variable-relative directory prefixes (``--data /x/y/lr-sets`` -> ``--data lr-sets``),
    leaving level names (``wB97M-V/def2-TZVPD``), units (``meV/A``) and URLs alone."""
    return _DIRS.sub("", s)


def code_commit() -> Optional[str]:
    """The git commit of the lrbench source that is running, ``+dirty`` if it has uncommitted changes; None when
    lrbench is not run from a git checkout (an installed wheel), in which case ``lrbench_version`` is all there is."""
    here = os.path.dirname(os.path.realpath(__file__))
    try:
        run = lambda *a: subprocess.run(["git", "-C", here, *a], capture_output=True, text=True, timeout=10)
        top = run("rev-parse", "--show-toplevel")
        # only this repository's own checkout: not a wheel in a venv inside some other project, not a vendored copy
        if top.returncode or os.path.realpath(os.path.join(top.stdout.strip(), "src", "lrbench")) != here \
                or run("ls-files", "--error-unmatch", "__init__.py").returncode:
            return None
        r = run("rev-parse", "HEAD")
        if r.returncode:
            return None
        dirty = run("status", "--porcelain", "--untracked-files=no", "--", ".").stdout.strip()
        return r.stdout.strip() + ("+dirty" if dirty else "")
    except Exception:
        return None


def spec_weights_file(spec: str) -> str:
    """The weights file a spec reads, for hashing: the spec itself for a path, else the ``path=`` / ``model=`` value
    of an ``ase:`` spec when it names an existing file (named models such as ``pet-omol-s`` carry one)."""
    if spec.startswith("mlipcpp-capi:"):
        return spec.split(":", 1)[1]
    if spec.startswith("ase:") and "?" in spec:
        for kv in spec.split("?", 1)[1].split("&"):
            k, _, v = kv.partition("=")
            v = os.path.expanduser(os.path.expandvars(v.strip().strip("'\"")))
            if k in ("path", "model") and os.path.isfile(v):
                return v
    return spec


def _walk_strings(o, where=""):
    if isinstance(o, str):
        yield where, o
    elif isinstance(o, dict):
        for k, v in o.items():
            yield from _walk_strings(k, f"{where}.{k}(key)")
            yield from _walk_strings(v, f"{where}.{k}")
    elif isinstance(o, (list, tuple)):
        for i, v in enumerate(o):
            yield from _walk_strings(v, f"{where}[{i}]")


def _load(path, default=None):
    if not os.path.exists(path):
        return default
    with open(path) as f:
        return json.load(f)


def _dump(obj, path):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w") as f:
        json.dump(obj, f, indent=1, sort_keys=True)
        f.write("\n")


def cards(root: str, private: bool = False) -> Dict[str, dict]:
    """Set cards: the public ones, plus the private ones when asked (private never shadows public)."""
    out = dict(_load(os.path.join(root, PRIVATE, "sets.json"), {})) if private else {}
    out.update(_load(os.path.join(root, "sets.json"), {}))
    return out


