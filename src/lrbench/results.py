def add_set(name: str, data: str, root: str = "results", *, licence: str, public: bool, level: str = "",
            description: str = "", note: str = "", revision: Optional[str] = None) -> dict:
    """Create the card for a set, or append the current data revision to it. Returns the card.

    Public cards are for sets whose licence permits publishing derived numbers; anything else is a private card
    under ``results/private/`` and its rows can never be committed."""
    from .data import load_set
    if not _NAME.match(name):
        raise ValueError(f"set name {name!r}: letters, digits, . _ + - only")
    ds = load_set(name, data, revision)
    levels = ds.levels() or ([level] if level else [])
    if not levels:
        raise ValueError(f"{name}: no record carries an energy, so pass --level with the reference level")
    pub, prv = os.path.join(root, "sets.json"), os.path.join(root, PRIVATE, "sets.json")
    path, other = (pub, prv) if public else (prv, pub)
    if name in _load(other, {}):
        raise ValueError(f"{name}: already carded as {'private' if public else 'public'}; a set is one or the other")
    allc = _load(path, {})
    card = allc.get(name) or {"reference_level": levels, "licence": licence, "public": public,
                              "description": description, "revisions": []}
    if card["reference_level"] != levels:
        raise ValueError(f"{name}: reference level changed {card['reference_level']} -> {levels}; a set that changes "
                         "level is a new set, not a new revision")
    rev = {"jsonl_sha256": ds.source["jsonl_sha256"], "groups_sha256": ds.source["groups_sha256"],
           "n_records": len(ds.records), "n_groups": len(ds.groups),
           "date": datetime.date.today().isoformat(), "note": note or ("initial" if not card["revisions"] else "")}
    if not any(_same_data(r, rev) for r in card["revisions"]):
        card["revisions"].append(rev)
    allc[name] = card
    _dump(allc, path)
    return card


def _same_data(a: dict, b: dict) -> bool:
    return a.get("jsonl_sha256") == b.get("jsonl_sha256") and a.get("groups_sha256") == b.get("groups_sha256")


# --------------------------------------------------------------------------------------------------------- rows

def row_from_result(R: dict, set_name: str, model: str = "", commit: str = "") -> dict:
    """One row (one model x one set) from an ``lrbench eval`` result JSON, with every directory prefix stripped."""
    from .report import headline_rows
    if set_name not in R.get("sets", {}):
        raise ValueError(f"set {set_name!r} is not in this result (has {sorted(R.get('sets', {}))})")
    S = R["sets"][set_name]
    lv = R.get("level") or {}
    commit = commit or R.get("code_commit") or ""
    if not commit:
        raise ValueError("the result records no code_commit (it predates lrbench recording one, or ran from an "
                         "installed wheel): pass --commit with the commit that produced it, deliberately")
    members = []
    for m in R.get("members", []):
        ext = m.get("external_model") or {}
        members.append({"spec": strip_dirs(m.get("spec", "")), "sha256": m.get("sha256"),
                        "backend": m.get("backend") or m.get("calculator"),
                        "package": ext.get("package"), "version": ext.get("version"),
                        "checkpoint": strip_dirs(ext.get("checkpoint") or "") or None,
                        "charge_spin": m.get("charge_spin", ext.get("charge_spin"))})
    src = (R.get("data") or {}).get(set_name) or S.get("source") or {}
    E = S.get("E_int") or {}
    n_failed = _n_failed(S)
    notes = [strip_dirs(x) for x in R.get("notes", [])]
    if n_failed and not any("fail" in x for x in notes):
        notes.append(f"{n_failed} predictions or groups failed on {set_name} and are not scored")
    pref = f"{set_name}: "
    metrics = [{"metric": a[len(pref):], "value": b, "n": c, "note": d}
               for a, b, c, d in headline_rows({"sets": {set_name: S}}) if a.startswith(pref)]
    n = len(R.get("members", [])) or 1
    return {
        "schema": SCHEMA, "set": set_name, "model": model or R.get("label") or "", "label": R.get("label") or model,
        "members": members, "model_level": lv.get("model_level") or "unknown",
        "reference_level": (lv.get("label_levels") or {}).get(set_name) or S.get("levels") or [],
        "level_mismatch": bool((lv.get("mismatch") or {}).get(set_name)), "seeds": n,
        "evidence": "claim" if n >= CLAIM_SEEDS else "screen",
        "n_failed": n_failed, "n_scored": int(E.get("n") or S.get("n_groups") or 0),
        "date": (R.get("created") or datetime.date.today().isoformat())[:10], "code_commit": commit,
        "lrbench_version": R.get("lrbench_version", "?"),
        "data": {"jsonl_sha256": src.get("jsonl_sha256"), "groups_sha256": src.get("groups_sha256"),
                 "revision": src.get("revision")},
        "argv": [strip_dirs(a) for a in R.get("argv", [])],
        "metrics": metrics,
        "notes": notes,
    }


def _n_failed(S: dict) -> int:
    """The largest failure count the set block reports: backend errors, groups that could not be evaluated (a None or
    non-finite energy with no error string), and a backend's own ``failures`` record where it writes one."""
    counts = [S.get("n_prediction_errors") or 0]
    counts += [(S.get(k) or {}).get("n_failed") or 0 for k in ("E_int", "ddE", "dE")]
    f = S.get("failures")
    counts.append(f if isinstance(f, int) else len(f) if isinstance(f, (list, dict)) else 0)
    return int(max(counts))


def _registry_spec(name: str) -> Optional[str]:
    """The adapter spec of a *released* model: membership in the named-model table, nothing looser (aliases, GGUF
    build registries and the like resolve names too, but do not make a model released)."""
    from .models import MODELS
    m = MODELS.get(name)
    return m.spec if m else None


#: A metric whose label says it was not scored is a *report*, not a measurement: a count of records the harness
#: flagged and refused to score. Some sets consist only of those.
def scored_metrics(row: dict) -> List[dict]:
    """The metrics in a row that are measurements rather than counts of what was refused."""
    return [m for m in (row.get("metrics") or [])
            if isinstance(m, dict) and "not scored" not in str(m.get("metric", "")).lower()]


def add(result_path: str, root: str = "results", sets: Optional[List[str]] = None, model: str = "",
        commit: str = "", private: bool = False) -> List[str]:
    """Write one row per set of a result JSON; returns the paths written. Each row is validated before it is
    written, so a row that would fail ``lrbench results check`` is never created."""
    R = _load(result_path)
    out = []
    for s in sets or list(R.get("sets", {})):
        row = row_from_result(R, s, model, commit)
        sub = os.path.join(root, PRIVATE) if private else root
        path = os.path.join(sub, s, f"{row['model']}.json")
        # A row whose every metric is a "not scored" count measures nothing. `pathology_h2o2p` is entirely such
        # counts for every model, so a row for it would publish a model's name beside no result at all -- and a
        # reader scanning a results table does not distinguish "flagged 8 records" from "scored 8". Skipping is
        # also right when a model failed on everything the set has: there is no result to report, only an absence.
        if not scored_metrics(row):
            print(f"[results] {s}/{row['model']}: nothing scored (every metric is a refusal count); no row written",
                  file=sys.stderr)
            continue
        errs = validate_row(row, root, path, private=private)
        if errs:
            raise ValueError(f"{path}: not written:\n  " + "\n  ".join(errs))
        _dump(row, path)
        out.append(path)
    return out


def validate_row(row: dict, root: str, path: str = "", private: bool = False) -> List[str]:
    """Every reason this row may not be committed (or, for a private row, used). Empty = valid."""
    from .data import UNSCORABLE_LEVELS
    e = []
    extra, missing = set(row) - ROW_KEYS, ROW_KEYS - set(row)
    if extra:
        e.append(f"unknown keys {sorted(extra)} (schema {SCHEMA})")
    if missing:
        e.append(f"missing keys {sorted(missing)}")
        return e
    if row["schema"] != SCHEMA:
        e.append(f"schema {row['schema']!r} != {SCHEMA!r}")
    if path:
        parts = os.path.normpath(path).split(os.sep)
        if parts[-2:] != [row["set"], f"{row['model']}.json"]:
            e.append(f"path must be <root>/{'private/' if private else ''}{row['set']}/{row['model']}.json")
    for k in ("set", "model"):
        if not _NAME.match(row[k] or ""):
            e.append(f"{k} {row[k]!r}: letters, digits, . _ + - only")
    for where, s in _walk_strings(row):
        if _ABS.search(s):
            e.append(f"{where}: contains a directory path ({s[:80]!r}); rows must carry no paths")
    card = cards(root, private=private).get(row["set"])
    if card is None:
        e.append(f"set {row['set']!r} has no card in {root}/sets.json" + (" or private/sets.json" if private else "")
                 + " (lrbench results add-set)")
    else:
        if not private and not card.get("public"):
            e.append(f"set {row['set']!r} is not public: its rows belong in {root}/private/")
        if sorted(card["reference_level"]) != sorted(row["reference_level"]):
            e.append(f"reference level {row['reference_level']} != the set card's {card['reference_level']}")
        if not any(_same_data(r, row["data"]) for r in card["revisions"]):
            e.append("data sha256 matches no revision on the set card: scored on data nobody carded "
                     "(lrbench results add-set records a new revision)")
    if not isinstance(row["seeds"], int) or row["seeds"] < 1:
        e.append("seeds must be a positive integer")
    elif row["evidence"] != ("claim" if row["seeds"] >= CLAIM_SEEDS else "screen"):
        e.append(f"evidence must be {'claim' if row['seeds'] >= CLAIM_SEEDS else 'screen'} for {row['seeds']} seed(s)")
    if not isinstance(row["n_failed"], int) or row["n_failed"] < 0:
        e.append("n_failed must be a non-negative integer")
    elif row["n_failed"] and not any("fail" in n for n in row["notes"]):
        e.append("n_failed > 0 but no note says what failed")
    known = row["model_level"] not in UNSCORABLE_LEVELS
    differs = known and any(x != row["model_level"] and x not in UNSCORABLE_LEVELS for x in row["reference_level"])
    if differs and not row["level_mismatch"]:
        e.append(f"model level {row['model_level']!r} differs from {row['reference_level']} but level_mismatch is false")
    if not _COMMIT.match(row["code_commit"] or ""):
        e.append(f"code_commit {row['code_commit']!r}: a clean git commit is required (no +dirty)")
    if not re.match(r"^\d{4}-\d{2}-\d{2}$", row["date"] or ""):
        e.append("date must be YYYY-MM-DD")
    if not row["members"] or len(row["members"]) != row["seeds"]:
        e.append("one member per seed")
    if not row["metrics"]:
        e.append("no metrics: the result has no headline rows for this set")
    if not private:
        spec = _registry_spec(row["model"])
        if spec is None:
            e.append(f"model {row['model']!r} is not a released model in the registry (lrbench models); rows for "
                     f"unreleased models belong in {root}/private/")
        elif any(mb.get("spec") != strip_dirs(spec) for mb in row["members"]):
            e.append(f"members were not run with the registry spec of {row['model']!r} ({strip_dirs(spec)}): a row "
                     "cannot relabel another model's result")
        for i, mb in enumerate(row["members"]):
            hashed = _HEX.match(mb.get("sha256") or "")
            versioned = mb.get("package") and mb.get("version") not in (None, "", "?")
            if not (hashed or versioned):
                e.append(f"members[{i}]: no weights sha256 and no package version: the model cannot be identified "
                         "(do not use --no-hash for a published row)")
    return e


def rows(root: str, private: bool = False) -> List[tuple]:
    """(path, row) for every row file under root (and root/private when asked)."""
    out = []
    bases = [(root, False)] + ([(os.path.join(root, PRIVATE), True)] if private else [])
    for base, priv in bases:
        if not os.path.isdir(base):
            continue
        for s in sorted(os.listdir(base)):
            d = os.path.join(base, s)
            if not os.path.isdir(d) or (s == PRIVATE and not priv):
                continue
            for f in sorted(os.listdir(d)):
                out.append((os.path.join(d, f), priv))
    return out


def check(root: str = "results", private: bool = False) -> List[str]:
    """Validate every row and card; returns the error lines (empty = all valid)."""
    errs = []
    for name, card in cards(root, private).items():
        if set(card) != CARD_KEYS:
            errs.append(f"sets.json[{name}]: keys must be {sorted(CARD_KEYS)}")
        elif not card["revisions"]:
            errs.append(f"sets.json[{name}]: no revisions")
    for where, s in _walk_strings(_load(os.path.join(root, "sets.json"), {})):
        if _ABS.search(s):
            errs.append(f"sets.json{where}: contains a directory path")
    for path, priv in rows(root, private):
        if not path.endswith(".json"):
            errs.append(f"{path}: only <set>/<model>.json row files belong here")
            continue
        try:
            row = _load(path)
        except ValueError as x:
            errs.append(f"{path}: not JSON ({x})")
            continue
        errs += [f"{path}: {m}" for m in validate_row(row, root, path, private=priv)]
    return errs


# --------------------------------------------------------------------------------------------------------- render

def _flags(row: dict, card: dict) -> str:
    f = []
    if row["level_mismatch"]:
        f.append(f"LEVEL MISMATCH (model {row['model_level']})")
    if row["n_failed"]:
        # n_scored counts energy groups, so a set that scores no energies at all -- charge_parity measures forces
        # -- has none by construction, and calling that "0 % coverage" would describe the set, not the model.
        if not row["n_scored"]:
            f.append(f"{row['n_failed']} failed; no energy groups in this set")
        else:
            attempted = row["n_failed"] + row["n_scored"]
            cov = row["n_scored"] / attempted
            if cov < MIN_COVERAGE:
                f.append(f"THIN COVERAGE: {row['n_scored']} of ~{attempted} scored ({cov:.0%})")
            else:
                f.append(f"{row['n_failed']} failed ({cov:.0%} scored)")
    f.append(f"{row['evidence']} ({row['seeds']} seed{'s' if row['seeds'] != 1 else ''})")
    if card and not _same_data(card["revisions"][-1], row["data"]):
        f.append("STALE: scored on an earlier revision")
    return "; ".join(f)


def summary_md(root: str = "results", private: bool = False) -> str:
    """The results tables: per set, one provenance line per model, then metric rows x model columns."""
    C = cards(root, private)
    by_set: Dict[str, List[dict]] = {}
    for path, _ in rows(root, private):
        if path.endswith(".json"):
            r = _load(path)
            by_set.setdefault(r["set"], []).append(r)
    n_rows = sum(len(v) for v in by_set.values())
    n_claim = sum(1 for v in by_set.values() for r in v if r.get("evidence") == "claim")
    out = ["# Results", ""]
    # Said once, at the top, in the place a visitor actually reads. The per-row flags were already honest, but a
    # table of numbers invites being read as a leaderboard whatever its footnotes say, and every row here is a
    # single seed.
    if n_rows and not n_claim:
        out += ["> [!IMPORTANT]",
                f"> **These are screens, not a ranking.** Every row below rests on **one seed**, where "
                f"{CLAIM_SEEDS} are needed before a number is a claim. They are useful for telling *has long-range "
                "physics* from *has none* -- the gap this benchmark measures is large and the diagnostics have "
                "known-correct values -- and they are not a basis for ordering models against one another. "
                "Rows also carry their own flags: a level of theory that differs from the references, and coverage "
                "below 75 % of the set where a model's element support drops whole systems.", ""]
    elif n_rows and n_claim < n_rows:
        out += ["> [!IMPORTANT]",
                f"> **{n_rows - n_claim} of {n_rows} rows are screens, not claims** -- a single seed each, where "
                f"{CLAIM_SEEDS} are needed for a claim. The flag on each row says which it is.", ""]
    out += ["Generated by `lrbench results render` from the row files in this directory; do not edit by hand. "
            "Values are estimate [95 % hierarchical-bootstrap interval]. A row with fewer than "
            f"{CLAIM_SEEDS} seeds is a screen, not a claim.", ""]
    if not by_set:
        out += ["No rows yet. See [docs/results.md](../docs/results.md) for how to add one.", ""]
    for s in sorted(by_set):
        card = C.get(s) or {}
        R = sorted(by_set[s], key=lambda r: r["model"])
        cur = (card.get("revisions") or [{}])[-1]
        out += [f"## {s}", "",
                f"Reference level {', '.join(card.get('reference_level', []))}; licence {card.get('licence', '?')}; "
                f"current revision `{(cur.get('jsonl_sha256') or '?')[:12]}` ({cur.get('n_groups', '?')} groups).", "",
                "| model | model level | date | commit | flags |", "|---|---|---|---|---|"]
        out += [f"| `{r['model']}` | {r['model_level']} | {r['date']} | `{r['code_commit'][:7]}` | {_flags(r, card)} |"
                for r in R]
        keys = list(dict.fromkeys(m["metric"] for r in R for m in r["metrics"]))
        if keys:
            val = [{m["metric"]: m["value"] for m in r["metrics"]} for r in R]
            out += ["", "| metric | " + " | ".join(f"`{r['model']}`" for r in R) + " |", "|---" * (len(R) + 1) + "|"]
            out += ["| " + " | ".join([k.replace("|", "\\|")] + [v.get(k, "–") for v in val]) + " |" for k in keys]
        out.append("")
    return "\n".join(out)


def _public_models_md() -> str:
    """``lrbench models --md`` with the local checkpoint directories written back as the variables that set them,
    so the committed table names ``$LRBENCH_UPET_DIR`` rather than whoever rendered it's home directory."""
    from . import models as M
    md = M.requirements_md()
    defaults = {"LRBENCH_LES_MODELS": "~/.cache/lrbench/les", "LRBENCH_DPA4_DIR": "~/.cache/lrbench/dpa4",
                "LRBENCH_UPET_DIR": "~/.cache/lrbench/upet"}
    for var in defaults:
        v = os.environ.get(var)
        if v:
            md = md.replace(v, f"${var}")
    for var, d in defaults.items():
        md = md.replace(os.path.expanduser(d), f"${var}")
    return md.replace(os.path.expanduser("~"), "~")


def models_results_md(root: str = "results") -> str:
    """The 'what has been scored' block of docs/models.md: one line per set with committed rows."""
    by_set: Dict[str, List[str]] = {}
    for path, _ in rows(root):
        if path.endswith(".json"):
            r = _load(path)
            by_set.setdefault(r["set"], []).append(f"`{r['model']}`" + (" (screen)" if r["evidence"] == "screen" else ""))
    if not by_set:
        return "No result rows are committed yet; see [results.md](results.md) for how to add one."
    return "\n".join(["Committed result rows ([results/SUMMARY.md](../results/SUMMARY.md)):", ""] +
                     [f"- **{s}:** " + ", ".join(sorted(v)) for s, v in sorted(by_set.items())])


def splice(text: str, block: str, body: str) -> str:
    b, e = BEGIN.format(block), END.format(block)
    if b not in text or e not in text:
        raise ValueError(f"marker {b} ... {e} not found")
    head, rest = text.split(b, 1)
    return head + b + "\n" + body.strip("\n") + "\n" + e + rest.split(e, 1)[1]


def render(root: str = "results", docs: str = "docs/models.md", check_only: bool = False) -> List[str]:
    """Regenerate results/SUMMARY.md and the generated blocks of docs/models.md. With ``check_only``, write nothing
    and return the files that are out of date."""
    targets = {os.path.join(root, "SUMMARY.md"): summary_md(root) + "\n"}
    if docs and os.path.exists(docs):
        t = open(docs).read()
        t = splice(t, "models", _public_models_md())
        targets[docs] = splice(t, "results", models_results_md(root))
    stale = [p for p, txt in targets.items() if (open(p).read() if os.path.exists(p) else None) != txt]
    if not check_only:
        for p in stale:
            with open(p, "w") as f:
                f.write(targets[p])
    return stale


# --------------------------------------------------------------------------------------------------------- CLI

def add_parser(sub):
    p = sub.add_parser("results", help="committed result rows: add a row or a set card, check, render the tables")
    s = p.add_subparsers(dest="results_cmd", required=True)
    q = s.add_parser("add", help="result JSON (lrbench eval --out) -> results/<set>/<model>.json, validated")
    q.add_argument("result")
    q.add_argument("--set", action="append", dest="sets", help="only this set (repeatable; default: every set)")
    q.add_argument("--model", default="", dest="row_model", help="row name; must be a registry name for a public row (default: the "
                   "result's label, which is the name when eval was given one)")
    q.add_argument("--commit", default="", help="code commit that produced the result, for JSONs that predate "
                   "lrbench recording it")
    q.add_argument("--private", action="store_true", help="write under results/private/ (git-ignored)")
    q = s.add_parser("add-set", help="card a set, or record a new revision of it (new curves, relabels)")
    q.add_argument("name")
    q.add_argument("--data", required=True, help="the data dir (or 'hf') the rows are scored on")
    q.add_argument("--revision")
    q.add_argument("--licence", required=True)
    vis = q.add_mutually_exclusive_group(required=True)
    vis.add_argument("--public", action="store_true", help="the licence permits publishing derived numbers")
    vis.add_argument("--private", action="store_true", help="internal-only data: card and rows stay in private/")
    q.add_argument("--level", default="", help="reference level, when no record carries an energy")
    q.add_argument("--description", default="")
    q.add_argument("--note", default="", help="what changed in this revision, e.g. '+12 curves (Cl-/Br- pairs)'")
    for name, h in (("check", "validate every row and card"), ("render", "regenerate results/SUMMARY.md and the "
                                                                        "generated blocks of docs/models.md")):
        q = s.add_parser(name, help=h)
        if name == "check":
            q.add_argument("--private", action="store_true", help="include results/private/")
        else:
            q.add_argument("--docs", default="docs/models.md")
            q.add_argument("--check", action="store_true", help="write nothing; exit 1 if anything is out of date")
    for q in s.choices.values():
        q.add_argument("--root", default="results")
    p.set_defaults(func=main)
    v = sub.add_parser("validate", help="alias of 'lrbench results check'")
    v.add_argument("--root", default="results")
    v.add_argument("--private", action="store_true")
    v.set_defaults(func=main, results_cmd="check")


def main(args: argparse.Namespace):
    c = args.results_cmd
    if c == "add":
        for p in add(args.result, args.root, args.sets, args.row_model, args.commit, args.private):
            print(p)
        print("next: lrbench results render", file=sys.stderr)
    elif c == "add-set":
        card = add_set(args.name, args.data, args.root, licence=args.licence, public=args.public, level=args.level,
                       description=args.description, note=args.note, revision=args.revision)
        print(json.dumps(card["revisions"][-1], indent=1))
    elif c == "check":
        errs = check(args.root, args.private)
        print("\n".join(errs) if errs else f"{args.root}: all rows and set cards valid")
        if errs:
            raise SystemExit(1)
    elif c == "render":
        stale = render(args.root, args.docs, check_only=args.check)
        if args.check and stale:
            raise SystemExit("out of date (run lrbench results render): " + ", ".join(stale))
        print("\n".join(stale) if stale else "up to date")
