#!/usr/bin/env python3
"""Build the GitHub Pages site: the committed results as a page, plus the notebook as WebAssembly.

    python tools/build_pages.py [-o site/]            # results page only
    marimo export html-wasm notebooks/long_range_diagnostics.py --mode run -o site/notebook/

``site/explorer/`` is committed, not built here: it needs the per-structure predictions of each run, which are not in
the repository. Regenerate it after adding rows, from the runs those rows came from:

    python tools/build_chemiscope_views.py RUNS_DIR --rows results --data DATA -o site/explorer/index.html

The results page is ``results/SUMMARY.md`` rendered to HTML, so it shows exactly the committed, validated rows and
nothing else. No raw result JSON is ever read here: those carry host names and absolute paths, and the rows have
already had them stripped. The notebook is the generator (no data embedded); it is published so that it can be
opened without an install.
"""
from __future__ import annotations

import argparse
import datetime
import html
import pathlib
import re
import subprocess

import markdown

HERE = pathlib.Path(__file__).resolve().parent.parent
REPO = "https://github.com/EricBoittier/LongRangeBench"

PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>LongRangeBench results</title>
<style>
:root {{ --bg:#fdfdfc; --fg:#1c1c1a; --muted:#66645e; --rule:#dddbd4; --accent:#2b5c8a; --flag:#9a3412; }}
@media (prefers-color-scheme: dark) {{
  :root {{ --bg:#16171a; --fg:#e6e5e1; --muted:#a3a19a; --rule:#34353a; --accent:#8db6e0; --flag:#f0a070; }}
}}
html {{ background:var(--bg); color:var(--fg); }}
body {{ font:15px/1.55 system-ui,-apple-system,"Segoe UI",sans-serif; max-width:1100px; margin:0 auto;
        padding:24px 16px 64px; background:var(--bg); }}
a {{ color:var(--accent); }}
header p, footer {{ color:var(--muted); }}
nav a {{ margin-right:1.2em; }}
h1 {{ font-size:1.6em; margin-bottom:.2em; }}
h2 {{ font-size:1.25em; margin-top:2em; border-bottom:1px solid var(--rule); padding-bottom:.2em; }}
.table-wrap {{ overflow-x:auto; }}
blockquote.callout {{ margin:1.4em 0; padding:.85em 1.1em; border-left:4px solid #b07c2a;
  background:rgba(176,124,42,.09); border-radius:0 4px 4px 0; }}
blockquote.callout p {{ margin:0; }}
blockquote.callout.important {{ border-left-color:#b07c2a; }}
blockquote.callout.note {{ border-left-color:#6e7073; background:rgba(110,112,115,.08); }}
table {{ border-collapse:collapse; font-variant-numeric:tabular-nums; font-size:13px; margin:.8em 0; }}
th, td {{ padding:4px 10px; border-bottom:1px solid var(--rule); text-align:left; vertical-align:top; }}
th {{ font-weight:600; border-bottom:2px solid var(--fg); }}
code {{ font-size:.92em; }}
strong {{ color:var(--flag); }}
footer {{ margin-top:3em; font-size:13px; border-top:1px solid var(--rule); padding-top:1em; }}
</style>
</head>
<body>
<header>
<nav><a href="./">Results</a><a href="explorer/">Explorer</a><a href="notebook/">Diagnostics notebook</a><a href="{repo}">Repository</a></nav>
<h1>LongRangeBench results</h1>
<p>Every number below comes from a validated row file in
<a href="{repo}/tree/main/results"><code>results/</code></a>, regenerated by <code>lrbench results render</code>.
Diagnostics have known right answers: tail fraction 1, normalised tail error ε 0, fixed-charge ΔΔE slope 1.
How to read them: <a href="{repo}/blob/main/docs/metrics.md">docs/metrics.md</a>.</p>
</header>
<main>
{body}
</main>
<footer>Built from commit <a href="{repo}/commit/{sha}"><code>{short}</code></a> on {date}.
Results are CC0; reference data and model weights keep their own licences, recorded in each row.</footer>
</body>
</html>
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("-o", "--out", default="site")
    a = ap.parse_args()
    src = (HERE / "results" / "SUMMARY.md").read_text()
    # the summary's own title is replaced by the page header; its relative links point into the repository
    lines = src.splitlines()
    if lines and lines[0].startswith("# "):
        lines = lines[1:]
    src = "\n".join(lines).replace("](../", f"]({REPO}/blob/main/")
    body = markdown.markdown(src, extensions=["tables", "fenced_code"])
    body = body.replace("<table>", '<div class="table-wrap"><table>').replace("</table>", "</table></div>")
    # GitHub renders "> [!IMPORTANT]" as a callout; python-markdown does not, and would publish the literal
    # "[!IMPORTANT]" inside a plain blockquote. The caveat that these rows are screens rather than a ranking is the
    # one thing on this page that must not look like an aside, so it is given the callout it is written as.
    body = re.sub(r'<blockquote>\s*<p>\s*\[!(\w+)\]\s*(?:<br\s*/?>)?\s*',
                  lambda m: f'<blockquote class="callout {m.group(1).lower()}"><p>', body)
    try:
        sha = subprocess.run(["git", "rev-parse", "HEAD"], cwd=HERE, capture_output=True, text=True,
                             check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        sha = "unknown"
    out = pathlib.Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "index.html").write_text(PAGE.format(body=body, repo=REPO, sha=html.escape(sha), short=sha[:7],
                                                date=datetime.date.today().isoformat()))
    (out / ".nojekyll").write_text("")
    print(f"wrote {out / 'index.html'}")


if __name__ == "__main__":
    main()
